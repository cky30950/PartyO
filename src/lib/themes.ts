export const THEME_MAP: Record<AppTheme, ThemeTokens> = THEME_LIST.reduce(
  (acc, item) => {
    acc[item.id] = item;
    return acc;
  },
  {} as Record<AppTheme, ThemeTokens>
);

export function isValidAppTheme(val: unknown): val is AppTheme {
  return typeof val === 'string' && val in THEME_MAP;
}

export function getThemeTokens(theme?: AppTheme | null): ThemeTokens {
  if (theme && theme in THEME_MAP) return THEME_MAP[theme];
  return THEME_MAP.tavern;
}

/**
 * 將選定的主題 CSS 變數即時套用到整頁 documentElement
 */
export function applyThemeToDocument(theme: AppTheme): void {
  const t = getThemeTokens(theme);
  const root = document.documentElement;
  root.dataset.theme = t.id;
  root.dataset.themeMode = t.mode;

  const vars: Record<string, string> = {
    '--t-bg': t.bg,
    '--t-bg-dot1': t.bgDot1,
    '--t-bg-dot2': t.bgDot2,
    '--t-surface': t.surface,
    '--t-surface-subtle': t.surfaceSubtle,
    '--t-surface-muted': t.surfaceMuted,
    '--t-ink': t.ink,
    '--t-ink-2': t.ink2,
    '--t-ink-muted': t.inkMuted,
    '--t-heading': t.heading,
    '--t-border': t.border,
    '--t-border-soft': t.borderSoft,
    '--t-shadow': t.shadow,
    '--t-bar-from': t.barFrom,
    '--t-bar-to': t.barTo,
    '--t-bar-text': t.barText,
    '--t-bar-sub': t.barSub,
    '--t-accent': t.accent,
    '--t-accent-hover': t.accentHover,
    '--t-accent-text': t.accentText,
    '--t-nav-bg': t.navBg,
    '--t-nav-active-bg': t.navActiveBg,
    '--t-nav-active-border': t.navActiveBorder,
    '--t-nav-active-text': t.navActiveText,
    '--t-input-bg': t.inputBg,
    '--t-input-border': t.inputBorder,
    '--t-card-radius': t.cardRadius,
    '--t-btn-radius': t.btnRadius,
    '--t-badge-bg': t.badgeBg,
    '--t-badge-text': t.badgeText,
  };

  for (const [k, v] of Object.entries(vars)) {
    root.style.setProperty(k, v);
  }

  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) {
    meta.setAttribute('content', t.themeColor);
  }
}
